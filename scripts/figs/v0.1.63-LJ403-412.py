def man(fig, x, base, h=52, head=7, color=BR):
    """立于 base 线上的人形；从头到脚共 h。"""
    fig.ring(x, base - h, head, INK, 1.2)
    fig.line(x, base - h + head, x, base, color, 1.1)
    fig.line(x - 9, base - h + 18, x + 9, base - h + 18, LG, 0.9)


def house(fig, x, base, w=140, h=60, roof=36):
    fig.line(x, base - h, x, base, BR, 1.1)
    fig.line(x + w, base - h, x + w, base, BR, 1.1)
    fig.path("M%d,%d L%d,%d L%d,%d L%d,%d" % (x - 10, base - h, x + w / 2, base - h - roof,
                                              x + w + 10, base - h, x + w + 10, base - h + 6), BR, P, 1.1)
    fig.line(x + w / 2 - 15, base, x + w / 2 - 15, base - 28, BR, 0.9)
    fig.line(x + w / 2 + 15, base, x + w / 2 + 15, base - 28, BR, 0.9)


def gate(fig, x, y, w=110, h=140):
    fig.line(x, y, x, y + h, BR, 1.3)
    fig.line(x + w, y, x + w, y + h, BR, 1.3)
    fig.line(x - 12, y, x + w + 12, y, BR, 1.4)
    fig.line(x - 12, y + 8, x + w + 12, y + 8, BR, 1.0)


